import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as phone from '../utils/radarTarget';
import * as pi from '../pi-cache/src/radar/radarTarget';
import { RadarFeed as PhoneFeed } from '../utils/radarFeed';
import { RadarFeed as PiFeed } from '../pi-cache/src/radar/radarFeed';
const read = (file: string) => readFileSync(resolve(process.cwd(), file), 'utf8').replace(/\r\n/g, '\n');
describe('shared radar target policy', () => {
    it('is byte-identical and dependency-free, with a canonical source hash', () => {
        const source = read('utils/radarTarget.ts');
        expect(source).not.toMatch(/^\s*import\s|\brequire\(|\bimport\(/m);
        expect(read('pi-cache/src/radar/radarTarget.ts')).toBe(
            '// GENERATED by pi-cache/scripts/sync-radar-target.mjs. Edit utils/radarTarget.ts only.\n\n' + source,
        );
        expect(read('pi-cache/src/radar/syncedFrom.ts')).toContain(
            `sha256: '${createHash('sha256').update(source).digest('hex')}'`,
        );
        const feed = read('utils/radarFeed.ts');
        expect(read('pi-cache/src/radar/radarFeed.ts')).toBe(
            '// GENERATED by pi-cache/scripts/sync-radar-target.mjs. Edit utils/radarFeed.ts only.\n\n' + feed,
        );
        expect(read('pi-cache/src/radar/syncedFrom.ts')).toContain(
            `feedSha256: '${createHash('sha256').update(feed).digest('hex')}'`,
        );
    });
    it('runs a real relative-motion frame identically in both runtime modules', () => {
        const body = 'RATTM,01,1,0,R,10,180,R,0.2,6,N,Generated echo,T,,120000,A';
        const checksum = [...body]
            .reduce((value, c) => value ^ c.charCodeAt(0), 0)
            .toString(16)
            .padStart(2, '0');
        const now = Date.UTC(2026, 0, 2, 12);
        const context = { feedId: 'pi:generated:verified-vessel', receivedAt: now, now };
        const frame = `$${body}*${checksum}`;
        const own = {
            feedId: context.feedId,
            position: { lat: 50, lon: -1, at: now },
            heading: { trueDeg: 0, at: now },
            motion: { sogKn: 5, sogAt: now, cogTrueDeg: 0, cogAt: now },
        };
        const phoneReport = phone.parseRadarSentence(frame, context)!;
        const piReport = pi.parseRadarSentence(frame, context)!;
        expect(piReport).toEqual(phoneReport);
        expect(pi.qualifyRadarReport(piReport, own, now)).toEqual(phone.qualifyRadarReport(phoneReport, own, now));
        expect(pi.qualifyRadarReport(piReport, own, now + 16_000).motion).toBeNull();
    });
    it('runs the bounded input accumulator identically on phone and Pi', () => {
        const now = Date.UTC(2026, 0, 2, 12);
        const frame = (body: string) =>
            `$${body}*${[...body]
                .reduce((v, c) => v ^ c.charCodeAt(0), 0)
                .toString(16)
                .padStart(2, '0')}`;
        const a = new PhoneFeed('pi:generated:verified-vessel'),
            b = new PiFeed('pi:generated:verified-vessel');
        for (const body of [
            'GPRMC,120000,A,0000.000,N,17959.940,E,5,0,020126,,,A',
            'HEHDT,0,T',
            'RATTM,01,1,90,T,10,180,R,0.2,6,N,Generated echo,T,,120000,A',
        ]) {
            a.ingest(frame(body), now, now);
            b.ingest(frame(body), now, now);
        }
        expect(b.contacts(now)).toEqual(a.contacts(now));
        expect(b.contacts(now)[0].motion!.sogKn).toBeCloseTo(5, 12);
        expect(b.contacts(now + 16_000)).toEqual(a.contacts(now + 16_000));
    });
});

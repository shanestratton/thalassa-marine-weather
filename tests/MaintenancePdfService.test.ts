/**
 * The maintenance checklist and service history PDFs, drawn with jsPDF
 * primitives since 129-10. They were HTML through doc.html(); DOMPurify kept
 * only the <body>, so their stylesheet never applied and the emoji printed as
 * garbage. These read the new documents back page by page.
 */

const { buildChecklistPdf, buildServiceHistoryPdf, checklistRows } = __testing;
/**
 * The paper, not the module's own constants: nothing within 10 mm of an A4
 * page's top or bottom edge (297 mm), and nothing past the old page's right
 * margin, 24 CSS px of an 800 px page (6.3 mm) in from the right edge.
 */
const PAPER_BOTTOM_LIMIT = 297 - 10;
const PAPER_TOP_LIMIT = 10;
const RIGHT_EDGE = 210 - 6.3 + 0.1;

function expectOnPaper(doc: jsPDF): void {
    readPages(doc).forEach((page, index) => {
        for (const item of page.texts) {
            const where = `page ${index + 1}: ${item.text}`;
            expect(item.y, where).toBeLessThanOrEqual(PAPER_BOTTOM_LIMIT);
            expect(item.y, where).toBeGreaterThan(index === 0 ? 5 : PAPER_TOP_LIMIT);
            expect(textRight(doc, item), where).toBeLessThanOrEqual(RIGHT_EDGE);
        }
        for (const y of page.ruleYs) expect(y, `page ${index + 1} rule`).toBeLessThanOrEqual(PAPER_BOTTOM_LIMIT + 0.5);
        for (const image of page.images) {
            expect(image.top + image.height, `page ${index + 1} picture`).toBeLessThanOrEqual(PAPER_BOTTOM_LIMIT + 2);
            expect(image.x + image.width, `page ${index + 1} picture`).toBeLessThanOrEqual(RIGHT_EDGE + 1);
        }
    });
}
const NOW = new Date(PDF_FIXTURE_NOW);
const LONG_DATE = NOW.toLocaleDateString('en-GB', { day: '2-digit', month: 'long', year: 'numeric' });

let canvas: ReturnType<typeof installFakeCanvas>;
beforeEach(() => {
    vi.useFakeTimers({ now: PDF_FIXTURE_NOW, toFake: ['Date'] });
    canvas = installFakeCanvas();
});
afterEach(() => {
    canvas.restore();
    vi.useRealTimers();
    vi.restoreAllMocks();
});

const read = (doc: jsPDF) => readPages(doc).map(pageLines);
/** Each page's text runs: one per cell line (columns share a baseline, so lines would merge them). */
const cells = (doc: jsPDF) => readPages(doc).map((page) => page.texts.map((item) => item.text));

describe('maintenance checklist PDF', () => {
    it('prints the heading, the vessel line, the columns and every task, most urgent first', () => {
        const tasks = maintenanceTasks();
        const doc = buildChecklistPdf(tasks, MAINTENANCE_ENGINE_HOURS, MAINTENANCE_VESSEL, jsPDF, NOW);
        const pages = read(doc);
        expect(pages).toHaveLength(1);
        const page = pages[0];
        const runs = cells(doc)[0];
        // The anchor is a picture; the words are text.
        expect(page).toContain(' VESSEL MAINTENANCE CHECKLIST');
        expect(canvas.draws.map((draw) => draw.text)).toContain('⚓');
        expect(page).toContain(`${MAINTENANCE_VESSEL}  |  ${LONG_DATE}  |  Engine Hours: 1,198`);
        for (const label of ['TASK', 'NEXT DUE', 'NOTES / HOURS AT COMPLETION']) expect(runs).toContain(label);

        // Every task, in the urgency order the screen uses, each with its due.
        const order = checklistRows(tasks, MAINTENANCE_ENGINE_HOURS);
        const drawn = cells(doc)[0].join('\n');
        let from = 0;
        for (const task of order) {
            const at = drawn.indexOf(task.title.split(' — ')[0], from);
            expect(at, task.title).toBeGreaterThanOrEqual(0);
            from = at;
            expect(runs, clipboardDueText(task)).toContain(clipboardDueText(task));
        }
        expect(page).toContain(`Generated by Thalassa Marine Weather — ${LONG_DATE}`);
    });

    it('wraps a vessel name with no spaces instead of running it off the page', () => {
        const name = '長崎'.repeat(80);
        const doc = buildChecklistPdf(maintenanceTasks(), null, name, jsPDF, NOW);
        for (const image of readPages(doc)[0].images) expect(image.x + image.width).toBeLessThanOrEqual(210 - 5);
        expect(canvas.draws.map((draw) => draw.text).join('')).toContain(name);
    });

    it('says "—" for engine hours not entered', () => {
        const page = read(buildChecklistPdf(maintenanceTasks(), null, MAINTENANCE_VESSEL, jsPDF, NOW))[0];
        expect(page).toContain(`${MAINTENANCE_VESSEL}  |  ${LONG_DATE}  |  Engine Hours: —`);
    });

    it('runs forty jobs over two pages, repeats the column header, and keeps every row on the paper', () => {
        const tasks = longMaintenanceTasks();
        const doc = buildChecklistPdf(tasks, MAINTENANCE_ENGINE_HOURS, MAINTENANCE_VESSEL, jsPDF, NOW);
        const raw = readPages(doc);
        const pages = cells(doc);
        expect(pages.length).toBe(2);
        for (const page of pages) expect(page).toContain('NOTES / HOURS AT COMPLETION');
        for (const task of tasks.filter((item) => !item.title.includes('—'))) {
            expect(pages.flat().filter((text) => text === task.title).length, task.title).toBe(1);
        }
        expect(raw).toHaveLength(2);
        expectOnPaper(doc);
    });

    it('prints a task title and a vessel name in every script', () => {
        const draw = vi.spyOn(PdfTextWriter.prototype, 'draw');
        const doc = buildChecklistPdf(maintenanceTasks(), null, `Étoile ${GLOBAL_TEXT}`, jsPDF, NOW);
        const drawn = draw.mock.calls
            .map((call) => call[0] as string)
            .join(' ')
            .replace(/\s+/g, ' ');
        expect(drawn).toContain(`Étoile ${GLOBAL_TEXT}`);
        expect(drawn).toContain(`Service tender outboard — ${GLOBAL_TEXT}`);
        expect(
            readPages(doc)
                .flatMap((page) => page.texts)
                .filter((item) => item.garbled),
        ).toEqual([]);
        const pictured = canvas.draws.map((item) => item.text).join(' ');
        for (const place of [GLOBAL_PLACES.greek, GLOBAL_PLACES.cyrillic, GLOBAL_PLACES.japanese, GLOBAL_PLACES.thai]) {
            expect(pictured).toContain(place);
        }
        // A cell line with Hebrew or Arabic is one left-to-right paragraph
        // picture, so the bidi algorithm orders it as the screen does.
        const bidiPictures = canvas.draws.filter((item) => /[\u0590-\u06ff]/.test(item.text));
        expect(bidiPictures.length).toBeGreaterThan(0);
        expect(bidiPictures.map((item) => item.text).join(' ')).toContain(GLOBAL_PLACES.hebrew);
        expect(bidiPictures.map((item) => item.text).join(' ')).toContain(GLOBAL_PLACES.arabic);
        expect(canvas.draws.filter((item) => item.direction !== 'ltr')).toEqual([]);
        expectOnPaper(doc);
    });
});

describe('maintenance service history PDF', () => {
    it('prints every entry with its date, task, hours, notes and cost, then the total', () => {
        const history = maintenanceHistory();
        const doc = buildServiceHistoryPdf(history, MAINTENANCE_VESSEL, jsPDF, NOW);
        const pages = read(doc);
        const runs = cells(doc);
        const all = runs.flat();
        expect(pages[0]).toContain(' OFFICIAL VESSEL SERVICE HISTORY');
        expect(canvas.draws.map((draw) => draw.text)).toContain('📋');
        expect(pages[0]).toContain(`${MAINTENANCE_VESSEL}  |  Generated: ${LONG_DATE}  |  Entries: ${history.length}`);
        for (const page of runs) {
            for (const label of ['DATE', 'COMPLETED', 'TASK PERFORMED', 'ENGINE', 'HRS', 'NOTES / CONDITION', 'COST']) {
                expect(page, label).toContain(label);
            }
        }
        // The first entry's row, cell by cell, in column order.
        const first = all.indexOf('Change engine oil and filter');
        expect(all.slice(first - 1, first + 4)).toEqual([
            new Date(history[0].completed_at).toLocaleDateString('en-GB', {
                day: '2-digit',
                month: 'short',
                year: 'numeric',
            }),
            'Change engine oil and filter',
            '1,110',
            'Oil was clean; 7.5 L of 15W-40',
            '$142.50',
        ]);
        expect(all).toContain('Unknown Task');
        expect(all).toContain('$25.00');
        expect(all.join(' ').replace(/\s+/g, ' ')).toContain('so a search should expect two beacons.');
        for (let index = 1; index <= 30; index++) {
            expect(all.filter((text) => text === `Inspect and grease seacock ${index}`)).toHaveLength(1);
        }
        const total = all.indexOf('TOTAL EXPENDITURE');
        expect(all[total + 1]).toBe('$2692.00');
        expect(pages[pages.length - 1]).toContain(`Generated by Thalassa Marine Weather — ${LONG_DATE}`);
        expectOnPaper(doc);
    });

    it('prints no total row when nothing cost money', () => {
        const history = maintenanceHistory().map((entry) => ({ ...entry, cost: null }));
        const all = cells(buildServiceHistoryPdf(history, MAINTENANCE_VESSEL, jsPDF, NOW)).flat();
        expect(all).not.toContain('TOTAL EXPENDITURE');
    });
});

describe('maintenance PDF exports', () => {
    function captureShare(): { file: () => File | undefined } {
        let shared: File | undefined;
        Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
        Object.defineProperty(navigator, 'share', {
            configurable: true,
            value: vi.fn(async (data: { files: File[] }) => {
                shared = data.files[0];
            }),
        });
        return { file: () => shared };
    }

    it('shares the checklist as a PDF file, without doc.html()', async () => {
        // jsPDF copies its API methods onto each document it creates, so this sees doc.html().
        const html = vi.spyOn(jsPDF.API as unknown as { html: () => void }, 'html');
        vi.spyOn(MaintenanceService, 'getTasks').mockResolvedValue(maintenanceTasks());
        const share = captureShare();
        await exportChecklist(MAINTENANCE_ENGINE_HOURS, MAINTENANCE_VESSEL);
        expect(share.file()?.type).toBe('application/pdf');
        expect(share.file()?.name).toBe(`Maintenance_Checklist_${NOW.toISOString().slice(0, 10)}.pdf`);
        expect(html).not.toHaveBeenCalled();
    }, 10000);

    it('shares the service history with task titles joined in', async () => {
        const history = maintenanceHistory();
        vi.spyOn(MaintenanceService, 'getAllHistory').mockResolvedValue(history);
        vi.spyOn(MaintenanceService, 'getAllTasks').mockResolvedValue(
            maintenanceTasks().map((task, index) => ({ ...task, id: history[index]?.task_id ?? task.id })),
        );
        const draw = vi.spyOn(PdfTextWriter.prototype, 'draw');
        const share = captureShare();
        await exportServiceHistory(MAINTENANCE_VESSEL);
        expect(share.file()?.name).toBe(`Service_History_${NOW.toISOString().slice(0, 10)}.pdf`);
        const drawn = draw.mock.calls.map((call) => call[0] as string);
        expect(drawn).toContain(maintenanceTasks()[0].title);
    }, 10000);
});

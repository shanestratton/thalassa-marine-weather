// @vitest-environment node
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import * as phone from '../utils/anchorSafeZone';
import * as pi from '../pi-cache/src/anchorSafeZone';
import * as edge from '../supabase/functions/_shared/anchorSafeZone';
describe('one anchor safe-area rule on all keepers', () => {
    it('retains byte-identical canonical source behind the build mirrors', () => {
        const canonical = readFileSync('utils/anchorSafeZone.ts', 'utf8').replaceAll('\r\n', '\n');
        const digest = createHash('sha256').update(canonical).digest('hex');
        for (const file of ['pi-cache/src/anchorSafeZone.ts', 'supabase/functions/_shared/anchorSafeZone.ts']) {
            const contents = readFileSync(file, 'utf8').replaceAll('\r\n', '\n');
            expect(contents).toBe(
                `// GENERATED by pi-cache/scripts/sync-anchor-zone.mjs from utils/anchorSafeZone.ts.\n// SHA256 ${digest}\n${canonical}`,
            );
        }
    });
    it('gives the same refusal and wrapped-wedge result to phone, Pi and relay', () => {
        const frame = { latitude: 0, longitude: 179.9999, radiusM: 100 };
        const zone = {
            version: 1,
            kind: 'wedges',
            anchor: { latitude: frame.latitude, longitude: frame.longitude },
            exclusions: [{ startDeg: 350, sweepDeg: 20 }],
        };
        for (const test of [
            { value: zone, east: 0, north: 50 },
            { value: zone, east: 50, north: 0 },
            { value: zone, east: 110, north: 0 },
            { value: { ...zone, version: 2 }, east: 0, north: 0 },
        ]) {
            const point = phone.anchorZonePosition(frame, test.east, test.north)!;
            const answers = [phone, pi, edge].map((rule) => rule.anchorSafeZoneContains(test.value, frame, point));
            expect(answers[1]).toBe(answers[0]);
            expect(answers[2]).toBe(answers[0]);
        }
    });
});

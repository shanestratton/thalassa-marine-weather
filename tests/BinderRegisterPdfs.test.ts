describe('sharing the Stores and Equipment PDFs', () => {
    function captureShare(): { files: File[]; titles: string[] } {
        const seen = { files: [] as File[], titles: [] as string[] };
        Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
        Object.defineProperty(navigator, 'share', {
            configurable: true,
            value: vi.fn(async (data: { files: File[]; title: string }) => {
                seen.files.push(data.files[0]);
                seen.titles.push(data.title);
            }),
        });
        return seen;
    }

    it("shares Ship's Stores as a PDF named for the local day, titled with the boat's name", async () => {
        const share = captureShare();
        const outcome = await shareInventoryPdf({ items: storesItems(), vesselName: STORES_VESSEL });
        expect(outcome).toBe('shared');
        expect(share.files[0]?.type).toBe('application/pdf');
        expect(share.files[0]?.name).toBe(`Ships_Stores_${pdfFileDay(NOW)}.pdf`);
        expect(share.titles[0]).toBe(`Ship's Stores - ${STORES_VESSEL}`);
    }, 10000);

    it('sends no blank PDF: chosen categories with nothing in them are empty', async () => {
        const share = captureShare();
        const draws = spyDraws();
        const outcome = await shareInventoryPdf({
            items: storesItems(),
            categories: new Set(['Rigging']),
            vesselName: STORES_VESSEL,
        });
        expect(outcome).toBe('empty');
        expect(await shareInventoryPdf({ items: [], vesselName: STORES_VESSEL })).toBe('empty');
        expect(await exportEquipmentPdf([], STORES_VESSEL)).toBe('empty');
        expect(share.files).toEqual([]);
        expect(draws()).toEqual([]);
    });

    it("opens the iPhone's share sheet for both (jsPDF's save() did nothing there)", async () => {
        vi.mocked(Capacitor.isNativePlatform).mockReturnValue(true);
        vi.mocked(Filesystem.writeFile).mockClear();
        vi.mocked(Share.share).mockClear();
        const click = vi.spyOn(HTMLAnchorElement.prototype, 'click');
        expect(await shareInventoryPdf({ items: storesItems(), vesselName: STORES_VESSEL })).toBe('shared');
        expect(await exportEquipmentPdf(equipmentItems(), STORES_VESSEL)).toBe('shared');
        expect(vi.mocked(Filesystem.writeFile).mock.calls.map(([options]) => options.path)).toEqual([
            `Ships_Stores_${pdfFileDay(NOW)}.pdf`,
            `Equipment_Register_${pdfFileDay(NOW)}.pdf`,
        ]);
        expect(vi.mocked(Share.share).mock.calls.map(([options]) => options.title)).toEqual([
            `Ship's Stores - ${STORES_VESSEL}`,
            `Equipment Register - ${STORES_VESSEL}`,
        ]);
        // No download link behind the share sheet.
        expect(click).not.toHaveBeenCalled();
    }, 10000);

    it('downloads on the web with no share sheet', async () => {
        const created = vi.fn(() => 'blob:mock');
        Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: created });
        Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() });
        const downloads: string[] = [];
        const click = vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(function (this: HTMLElement) {
            downloads.push((this as HTMLAnchorElement).download);
        });
        expect(await exportEquipmentPdf(equipmentItems(), STORES_VESSEL)).toBe('downloaded');
        expect(click).toHaveBeenCalledOnce();
        expect(downloads).toEqual([`Equipment_Register_${pdfFileDay(NOW)}.pdf`]);
        expect(created).toHaveBeenCalledOnce();
    }, 10000);

    it('says cancelled, and downloads nothing, when the share sheet is dismissed', async () => {
        Object.defineProperty(navigator, 'canShare', { configurable: true, value: () => true });
        Object.defineProperty(navigator, 'share', {
            configurable: true,
            value: vi.fn(async () => {
                throw Object.assign(new Error('Share canceled'), { name: 'AbortError' });
            }),
        });
        const click = vi.spyOn(HTMLAnchorElement.prototype, 'click');
        expect(await shareInventoryPdf({ items: storesItems(), vesselName: STORES_VESSEL })).toBe('cancelled');
        expect(click).not.toHaveBeenCalled();
    }, 10000);
});

describe('the binder PDFs, at the source', () => {
    const ROOT = process.cwd();
    const FILES = [
        'utils/inventoryPdfExport.ts',
        'utils/equipmentPdfExport.ts',
        'services/MaintenancePdfService.ts',
        'services/pdf/registerPdf.ts',
        'services/pdf/pdfDates.ts',
    ];
    /** The code, without its comments (they tell the history, emoji and all). */
    const read = (file: string) =>
        readFileSync(join(ROOT, file), 'utf8')
            .replace(/\/\*[\s\S]*?\*\//g, '')
            .replace(/^\s*\/\/.*$/gm, '');

    it("write no fixed locale and never call jsPDF's save() or the share API themselves", () => {
        for (const file of FILES) {
            const text = read(file);
            expect(text, file).not.toMatch(/'en-(GB|AU|US)'/);
            expect(text, file).not.toMatch(/\.save\(/);
            expect(text, file).not.toMatch(/navigator\.share|sharePdfFile/);
            // A file's day is the local one, not the UTC one.
            expect(text, file).not.toMatch(/toISOString\(\)/);
        }
        for (const file of FILES.slice(0, 3)) expect(read(file), file).toMatch(/sharePdfBlob\(/);
    });

    it('carry no emoji', () => {
        for (const file of FILES) expect(EMOJI.test(read(file)), file).toBe(false);
    });

    it('Maintenance prints from the rows it is given, not the server service', () => {
        const text = read('services/MaintenancePdfService.ts');
        expect(text).not.toMatch(/MaintenanceService\.(getTasks|getAllTasks|getAllHistory)/);
    });
});

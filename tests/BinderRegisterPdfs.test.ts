/** Every PdfTextWriter.draw call: the logical text, whether drawn as text or as a picture. */
function spyDraws() {
    const draw = vi.spyOn(PdfTextWriter.prototype, 'draw');
    return () =>
        draw.mock.calls.map(([text, x, y, style]) => ({
            text: text as string,
            x: x as number,
            y: y as number,
            style: style as PdfTextStyle,
        }));
}

/** The lines drawn in one table column, in order, joined: what a cell's wrapped lines say together. */
function columnText(draws: ReturnType<ReturnType<typeof spyDraws>>, left: number): string {
    return draws
        .filter((draw) => draw.style.size === 7.5 && Math.abs(draw.x - (left + 2)) < 0.01)
        .map((draw) => draw.text)
        .join(' ');
}

/** Nothing past the rows' foot but the footer, nothing past a column's right edge, nothing garbled. */
function expectOnPaper(doc: jsPDF, widths: number[]): void {
    const { PAGE_BOTTOM, M } = registerTesting;
    const edges = widths.reduce<number[]>((acc, width) => [...acc, acc[acc.length - 1] + width], [M]);
    readPages(doc).forEach((page: PdfPage, index) => {
        for (const item of page.texts) {
            const where = `page ${index + 1}: ${item.text}`;
            expect(item.garbled, where).toBe(false);
            if (item.y > PAGE_BOTTOM) {
                expect(item.text, where).toMatch(/^Generated by Thalassa Marine Weather \| /);
                continue;
            }
            // A table cell stays inside its column (band and headings span the page).
            if (item.size === 7.5 || item.size === 5.5) {
                const column = edges.findIndex((edge, at) => item.x >= edge && item.x < edges[at + 1]);
                expect(column, where).toBeGreaterThanOrEqual(0);
                expect(textRight(doc, item), where).toBeLessThanOrEqual(edges[column + 1] + 0.01);
            }
        }
        for (const image of page.images) {
            expect(image.top + image.height, `page ${index + 1} picture`).toBeLessThanOrEqual(297 - 5);
        }
    });
}

describe("the Ship's Stores PDF", () => {
    const widths = storesTesting.COLUMNS.map((column) => column.width);
    /** A column's left edge, from the page margin (15 mm). */
    const left = (label: string) =>
        15 +
        storesTesting.COLUMNS.slice(
            0,
            storesTesting.COLUMNS.findIndex((column) => column.label === label),
        ).reduce((sum, column) => sum + column.width, 0);

    it("is titled Ship's Stores, with the boat's name, the categories, the date and the totals", () => {
        const doc = buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const first = pageLines(readPages(doc)[0]);
        expect(first).toContain("SHIP'S STORES");
        expect(first.join('\n')).not.toContain('INVENTORY');
        expect(first).toContain(`${STORES_VESSEL} | All Categories | ${LONG_DATE}`);
        // Items, not a sum of kilograms and flares (131-B14).
        expect(first).toContain('8 Items · 1 Low Stock');
        expect(first.join('\n')).not.toMatch(/Units|TOTAL UNITS/);
        expect(
            pageLines(readPages(doc)[0]).some((line) => line.startsWith('Generated by Thalassa Marine Weather')),
        ).toBe(true);
    });

    it("prints no stand-in 'Vessel' when the boat has no name", () => {
        const doc = buildStoresPdf({ items: storesItems() }, jsPDF, NOW);
        const first = pageLines(readPages(doc)[0]);
        expect(first).toContain(`All Categories | ${LONG_DATE}`);
        expect(first.join('\n')).not.toContain('Vessel');
    });

    it('prints a long name whole, wrapped in its column, never cut', () => {
        const draws = spyDraws();
        const doc = buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const names = columnText(draws(), 15);
        expect(names).toContain(LONG_STORES_NAME);
        const location = columnText(draws(), left('LOCATION'));
        expect(location).toContain('Nav station — Top drawer, red first-aid box behind the chart folio');
        // A zone-less location still prints its place.
        expect(location).toContain('Under the saloon sole');
        expectOnPaper(doc, widths);
    });

    it('prints no emoji, and a name in any script as the phone draws it', () => {
        const draws = spyDraws();
        const doc = buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const all = draws().map((draw) => draw.text);
        expect(all.filter((text) => EMOJI.test(text))).toEqual([]);
        expect(canvas.draws.filter((draw) => EMOJI.test(draw.text))).toEqual([]);
        expect(all).toContain('BOOZE (1)');
        const pictured = canvas.draws.map((draw) => draw.text).join(' ');
        for (const place of [GLOBAL_PLACES.greek, GLOBAL_PLACES.japanese, GLOBAL_PLACES.arabic]) {
            expect(pictured).toContain(place);
        }
        expectOnPaper(doc, widths);
    });

    it('writes an expiry as the phone writes dates, on that local day', () => {
        const draws = spyDraws();
        buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const flares = storesItems().find((item) => item.id === 's4');
        const [year, month, day] = (flares?.expiry_date ?? '').split('-').map(Number);
        const expected = new Date(year, month - 1, day).toLocaleDateString(undefined, {
            day: 'numeric',
            month: 'short',
            year: 'numeric',
        });
        const expiry = draws().filter((draw) => Math.abs(draw.x - (left('EXPIRY') + 2)) < 0.01);
        const flaresDate = expiry.find((draw) => draw.text === expected);
        expect(flaresDate).toBeDefined();
        // Forty days out: amber. Past: red.
        expect(flaresDate?.style.color).toBe('#d97706');
        const tablets = storesItems().find((item) => item.id === 's3');
        expect(expiry.find((draw) => draw.text === pdfShortDate(tablets?.expiry_date))?.style.color).toBe('#dc2626');
    });

    it("follows the phone's locale for every date and number", () => {
        const dates = vi.spyOn(Date.prototype, 'toLocaleDateString');
        const numbers = vi.spyOn(Number.prototype, 'toLocaleString');
        buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        expect(dates).toHaveBeenCalled();
        for (const call of dates.mock.calls) expect(call[0]).toBeUndefined();
        for (const call of numbers.mock.calls) expect(call[0]).toBeUndefined();
    });

    it('marks low stock with LOW beside the count, clear of it', () => {
        const doc = buildStoresPdf({ items: storesItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const texts = readPages(doc)[0].texts;
        const low = texts.filter((item) => item.text === 'LOW');
        expect(low).toHaveLength(1);
        const count = texts.find((item) => item.text === '1' && Math.abs(item.y - low[0].y) < 0.01);
        expect(count).toBeDefined();
        expect(low[0].x).toBeGreaterThan(textRight(doc, count!));
        // Part units print as the phone writes numbers, with their unit.
        expect(texts.map((item) => item.text)).toContain(
            `${(2.5).toLocaleString(undefined, { maximumFractionDigits: 2 })} kg`,
        );
    });

    it('prints amounts in units, in the skipper’s unit system (131-B14)', () => {
        const sugar = {
            ...storesItems()[1],
            id: 'sugar',
            item_name: 'Raw sugar',
            quantity: 1000,
            min_quantity: 500,
            unit: 'g',
        };
        const milk = { ...storesItems()[1], id: 'milk', item_name: 'UHT milk', quantity: 1500, unit: 'ml' };
        const metric = pageLines(readPages(buildStoresPdf({ items: [sugar, milk] }, jsPDF, NOW))[0]).join('\n');
        expect(metric).toContain('1 kg');
        expect(metric).toContain('500 g');
        expect(metric).toContain(`${(1.5).toLocaleString(undefined, { maximumFractionDigits: 2 })} L`);
        expect(metric).not.toMatch(/\b1000\b|1,000/);

        const imperial = pageLines(
            readPages(buildStoresPdf({ items: [sugar, milk], units: 'imperial' }, jsPDF, NOW))[0],
        ).join('\n');
        expect(imperial).toContain(`${(2.2).toLocaleString(undefined, { maximumFractionDigits: 2 })} lb`);
        expect(imperial).toContain(`${(50.7).toLocaleString(undefined, { maximumFractionDigits: 1 })} fl oz`);
    });

    it('counts Low by the screen’s one rule: an empty row with no minimum is not low', () => {
        const empty = { ...storesItems()[1], id: 'empty', item_name: 'Spare shackle', quantity: 0, min_quantity: 0 };
        const doc = buildStoresPdf({ items: [empty] }, jsPDF, NOW);
        const first = pageLines(readPages(doc)[0]);
        expect(first).toContain('1 Item');
        expect(readPages(doc)[0].texts.map((item) => item.text)).not.toContain('LOW');
    });

    it('lists only the chosen categories, in the screen order', () => {
        const categories = new Set(['Medical', 'Safety'] as const);
        const draws = spyDraws();
        const doc = buildStoresPdf(
            { items: storesItems(), categories: new Set(categories), vesselName: STORES_VESSEL },
            jsPDF,
            NOW,
        );
        const first = pageLines(readPages(doc)[0]);
        expect(first).toContain(`${STORES_VESSEL} | Safety, Medical | ${LONG_DATE}`);
        const names = columnText(draws(), 15);
        expect(names).toContain('Handheld flares');
        expect(names).toContain('Seasickness tablets');
        expect(names).not.toContain('Basmati rice');
        expect(
            storesPdfItems({ items: storesItems(), categories: new Set(categories) }).map((item) => item.id),
        ).toEqual(['s3', 's4']);
    });

    it('runs a long list over pages with the column header on each and a page count', () => {
        const doc = buildStoresPdf({ items: longStoresItems(), vesselName: STORES_VESSEL }, jsPDF, NOW);
        const pages = readPages(doc);
        expect(pages.length).toBeGreaterThan(2);
        pages.forEach((page, index) => {
            expect(page.texts.map((item) => item.text)).toContain('ITEM');
            expect(pageLines(page)).toContain(
                `Generated by Thalassa Marine Weather | ${LONG_DATE} | Page ${index + 1} of ${pages.length}`,
            );
        });
        expectOnPaper(doc, widths);
    });

    it('carries a name taller than a page over, line by line, and keeps it on the paper', () => {
        const draws = spyDraws();
        const name = Array.from({ length: 900 }, (_, index) => `word${index}`).join(' ');
        const items = [{ ...storesItems()[1], id: 'huge', item_name: name }];
        const doc = buildStoresPdf({ items, vesselName: STORES_VESSEL }, jsPDF, NOW);
        expect(readPages(doc).length).toBeGreaterThan(1);
        expect(columnText(draws(), 15)).toBe(name);
        expectOnPaper(doc, widths);
    });
});


import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';

describe('wake rule pure shared graph', () => {
    it('copies each allowlisted source exactly, only adding Node import extensions', () => {
        const stamp = readFileSync(resolve('pi-cache/src/wakeRule/syncedFrom.ts'), 'utf8');
        for (const file of ['wakeRule.ts', 'wakeRuleInputs.ts', 'barometerTendency.ts', 'wakePiContract.ts']) {
            const source = readFileSync(resolve('utils', file), 'utf8').replace(/\r\n/g, '\n');
            const mirrored = readFileSync(resolve('pi-cache/src/wakeRule', file), 'utf8').replace(/\r\n/g, '\n');
            const header = `// GENERATED by pi-cache/scripts/sync-wake-rule.mjs from utils/${file}. Do not edit.\n`;
            expect(mirrored).toBe(
                header +
                    source.replace(
                        /\bfrom\s*(['"])(\.\/[^'"]+)\1/g,
                        (_, quote, specifier) => `from ${quote}${specifier}.js${quote}`,
                    ),
            );
            expect(stamp).toContain(`'utils/${file}': '${createHash('sha256').update(source).digest('hex')}'`);
        }
    });
    it('passes the executable drift gate used before packaging', () => {
        const result = execFileSync(process.execPath, ['pi-cache/scripts/sync-wake-rule.mjs', '--check'], {
            encoding: 'utf8',
            timeout: 10_000,
        });
        expect(result).toContain('4 allowlisted pure modules');
    });
});

import { LOCAL_CHART_FILE_BYTES } from './localChartLimits';

export const LOCAL_CHART_LIBRARY_BYTES = 64 * 1024 * 1024;
export const LOCAL_CHART_LIBRARY_COUNT = 8;
export const LOCAL_CHART_MANIFEST_BYTES = 16 * 1024;
export type LocalChartKind = 'mbtiles' | 'kap' | 'tif' | 'tiff';
export type LocalChartRights = 'own' | 'open';
export interface LocalChartRecord {
    id: string;
    name: string;
    kind: LocalChartKind;
    bytes: number;
    rights: LocalChartRights;
    importedAt: number;
    sha256: string;
}
export interface LocalChartManifest {
    schema: 1;
    ownerNamespace: string;
    charts: LocalChartRecord[];
}
const UUID = /^[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89ab][a-f0-9]{3}-[a-f0-9]{12}$/;
const object = (value: unknown): value is Record<string, unknown> =>
    !!value && typeof value === 'object' && !Array.isArray(value);
export function assertChartNamespace(value: string): void {
    if (!/^[a-f0-9]{32}$/.test(value)) throw new Error('Invalid chart owner.');
}
/** The retained basename is generated by the app; the display name is never a path. */
export function localChartPath(namespace: string, chart: Pick<LocalChartRecord, 'id' | 'kind'>): string {
    assertChartNamespace(namespace);
    if (!UUID.test(chart.id) || !['mbtiles', 'kap', 'tif', 'tiff'].includes(chart.kind)) {
        throw new Error('Invalid saved chart.');
    }
    return `chart-library/${namespace}/${chart.id}.${chart.kind}`;
}
export function localChartKind(name: string): LocalChartKind {
    if (
        name.length > 160 ||
        /[/\\]/.test(name) ||
        Array.from(name).some((c) => c.charCodeAt(0) < 32 || c.charCodeAt(0) === 127) ||
        name.includes('..')
    ) {
        throw new Error('Choose a local chart file.');
    }
    const kind = name.split('.').at(-1)?.toLowerCase();
    if (!kind || !['mbtiles', 'kap', 'tif', 'tiff'].includes(kind)) {
        throw new Error('Choose MBTiles, KAP or GeoTIFF. For BSB charts, choose the KAP image.');
    }
    return kind as LocalChartKind;
}
function record(value: unknown): LocalChartRecord {
    if (!object(value) || typeof value.name !== 'string' || !value.name.trim()) throw new Error('Invalid chart entry.');
    const kind = localChartKind(value.name);
    if (
        typeof value.id !== 'string' ||
        !UUID.test(value.id) ||
        value.kind !== kind ||
        typeof value.bytes !== 'number' ||
        !Number.isSafeInteger(value.bytes) ||
        value.bytes < 8 ||
        value.bytes > LOCAL_CHART_FILE_BYTES ||
        (value.rights !== 'own' && value.rights !== 'open') ||
        typeof value.importedAt !== 'number' ||
        !Number.isSafeInteger(value.importedAt) ||
        value.importedAt < 946684800000 ||
        value.importedAt > 4102444800000 ||
        typeof value.sha256 !== 'string' ||
        !/^[a-f0-9]{64}$/.test(value.sha256)
    )
        throw new Error('Invalid chart entry.');
    return {
        id: value.id,
        name: value.name,
        kind,
        bytes: value.bytes,
        rights: value.rights,
        importedAt: value.importedAt,
        sha256: value.sha256,
    };
}
/** Strict owner and size admission precedes any retained-file lookup or SQLite load. */
export function readLocalChartManifest(text: string, namespace: string): LocalChartManifest {
    assertChartNamespace(namespace);
    if (
        text.length > LOCAL_CHART_MANIFEST_BYTES ||
        new TextEncoder().encode(text).length > LOCAL_CHART_MANIFEST_BYTES
    ) {
        throw new Error('Saved chart index is too large.');
    }
    const value: unknown = JSON.parse(text);
    if (
        !object(value) ||
        value.schema !== 1 ||
        value.ownerNamespace !== namespace ||
        !Array.isArray(value.charts) ||
        value.charts.length > LOCAL_CHART_LIBRARY_COUNT
    ) {
        throw new Error('Invalid saved chart index.');
    }
    const charts = value.charts.map(record);
    if (
        new Set(charts.map((chart) => chart.id)).size !== charts.length ||
        charts.reduce((sum, chart) => sum + chart.bytes, 0) > LOCAL_CHART_LIBRARY_BYTES
    ) {
        throw new Error('Saved chart storage limit exceeded.');
    }
    return { schema: 1, ownerNamespace: namespace, charts };
}
export function addLocalChart(manifest: LocalChartManifest, candidate: LocalChartRecord): LocalChartManifest {
    // Re-admit both inputs: callers cannot bypass a limit with an in-memory DTO.
    return readLocalChartManifest(
        JSON.stringify({ ...manifest, charts: [...manifest.charts, candidate] }),
        manifest.ownerNamespace,
    );
}

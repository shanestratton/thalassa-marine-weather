-- Synthetic disposable schema only. No HTTP hooks, provider keys or sender.
CREATE ROLE anon;
CREATE ROLE authenticated;
CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
GRANT USAGE ON SCHEMA auth TO authenticated,service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO authenticated,service_role;
CREATE TABLE public.boats(id uuid PRIMARY KEY,owner_id uuid REFERENCES auth.users(id),archived_at timestamptz);
CREATE TABLE public.pi_diary_relays(relay_id text PRIMARY KEY,owner_id uuid,boat_id uuid,enabled boolean);
ALTER TABLE public.boats ENABLE ROW LEVEL SECURITY;
CREATE POLICY own ON public.boats FOR SELECT TO authenticated USING(owner_id=auth.uid());
GRANT SELECT ON public.boats TO authenticated;
CREATE TABLE public.push_notification_queue(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),recipient_user_id uuid,notification_type text,title text,body text,data jsonb);
CREATE SCHEMA cron;
CREATE TABLE cron.job(jobid bigint PRIMARY KEY,jobname text,active boolean,schedule text,command text);
CREATE TABLE cron.job_run_details(jobid bigint,status text,end_time timestamptz);

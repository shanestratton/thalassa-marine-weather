#!/usr/bin/env node
/** Canonical app ENC index and lookahead rule, copied only into the vault's
 * graph. The alarm process imports protocol types and bounded IPC instead. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const out = path.join(root, 'pi-cache/src/lookaheadShared');
const sources = [
    'services/enc/EncSpatialIndex.ts',
    'services/enc/encHazardParse.ts',
    'services/enc/hazardSeverity.ts',
    'services/enc/types.ts',
    'services/enc/chartDatum.ts',
    'services/underway/lookaheadRule.ts',
    'services/underway/lookaheadCoverage.ts',
    'services/underway/underwayRule.ts',
    'services/routeProgress.ts',
    'utils/navigationCalculations.ts',
    'utils/keelDepth.ts',
];
const prettier = process.env.PRETTIER_BIN || path.join(root, 'node_modules/prettier/bin/prettier.cjs');
const check = process.argv.includes('--check');
const format = (content, file) =>
    execFileSync(process.execPath, [prettier, '--stdin-filepath', file], {
        cwd: root,
        input: content,
        encoding: 'utf8',
    });
let failed = false;
const digest = createHash('sha256');
const generated = new Map();
for (const rel of sources) {
    const source = fs.readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/g, '\n');
    digest.update(rel + '\n' + createHash('sha256').update(source).digest('hex') + '\n');
    const body = source.replace(
        /(from\s+['"])(\.[^'"]+)(['"])/g,
        (_all, a, s, b) => a + s.replace(/\.ts$/, '').replace(/(?<!\.js)$/, '.js') + b,
    );
    generated.set(rel, '// GENERATED by pi-cache/scripts/sync-lookahead-rule.mjs from ' + rel + '.\n' + body);
}
generated.set(
    'types/navigation.ts',
    `// GENERATED type-only boundary; no app runtime imports.
export type NmeaDepthReference = 'below-keel' | 'below-transducer' | 'below-waterline';
`,
);
generated.set(
    'utils/createLogger.ts',
    `// GENERATED vault logger: no app runtime or network imports.
export function createLogger(_tag: string) {
    return {debug: (..._args: unknown[]) => {}, info: (..._args: unknown[]) => {}, warn: (...args: unknown[]) => console.warn(...args), error: (...args: unknown[]) => console.error(...args)};
}
`,
);
generated.set(
    'syncedFrom.ts',
    `// GENERATED by pi-cache/scripts/sync-lookahead-rule.mjs.
export const LOOKAHEAD_SOURCE_DIGEST = '${digest.digest('hex')}';
`,
);
for (const [rel, content] of generated) {
    const target = path.join(out, rel);
    const expected = format(content, target);
    if (check) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
            console.error('Lookahead mirror differs: ' + rel);
            failed = true;
        }
    } else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, expected);
    }
}
if (failed) process.exit(1);
console.log('Lookahead mirror ' + (check ? 'verified' : 'written') + ' (' + sources.length + ' canonical modules).');

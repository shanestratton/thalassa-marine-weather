#!/usr/bin/env node
/** Bounded pure graph mirror. No runtime/service imports may enter the Pi rule. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const target = path.join(repo, 'pi-cache/src/wakeRule');
const files = ['wakeRule.ts', 'wakeRuleInputs.ts', 'barometerTendency.ts'];
const allowedImports = new Map([
    ['wakeRule.ts', []],
    ['barometerTendency.ts', []],
    ['wakeRuleInputs.ts', ['./barometerTendency', './wakeRule']],
]);
const args = new Set(process.argv.slice(2));
if ([...args].some((arg) => !['--check', '--allow-dirty'].includes(arg)))
    throw new Error('Unsupported mirror argument');
const check = args.has('--check');
const hashes = {};
const output = [];
for (const file of files) {
    const relative = 'utils/' + file;
    const source = fs.readFileSync(path.join(repo, relative), 'utf8').replace(/\r\n/g, '\n');
    const tree = ts.createSourceFile(relative, source, ts.ScriptTarget.Latest, true);
    const imports = [];
    let forbidden = false;
    const visit = (node) => {
        if (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) {
            if (node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier))
                imports.push(node.moduleSpecifier.text);
            if (ts.isImportDeclaration(node) && !node.importClause) forbidden = true;
        }
        if (
            ts.isImportEqualsDeclaration(node) ||
            (ts.isCallExpression(node) &&
                (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
                    (ts.isIdentifier(node.expression) && node.expression.text === 'require')))
        )
            forbidden = true;
        ts.forEachChild(node, visit);
    };
    visit(tree);
    if (JSON.stringify(imports.sort()) !== JSON.stringify([...allowedImports.get(file)].sort()) || forbidden)
        throw new Error('Refusing non-allowlisted import in ' + relative);
    hashes[relative] = createHash('sha256').update(source).digest('hex');
    const rewritten = source.replace(
        /\bfrom\s*(['"])(\.\/[^'"]+)\1/g,
        (_, quote, specifier) => `from ${quote}${specifier}.js${quote}`,
    );
    output.push([
        path.join(target, file),
        `// GENERATED by pi-cache/scripts/sync-wake-rule.mjs from ${relative}. Do not edit.\n` + rewritten,
    ]);
}
const stampPath = path.join(target, 'syncedFrom.ts');
if (check) {
    for (const [file, contents] of output) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== contents)
            throw new Error('Wake rule mirror drift: ' + path.relative(repo, file));
    }
    const stamp = fs.readFileSync(stampPath, 'utf8');
    for (const [file, sha] of Object.entries(hashes))
        if (!stamp.includes(`'${file}': '${sha}'`)) throw new Error('Wake rule stamp drift: ' + file);
    console.info('Wake rule mirror is current (3 allowlisted pure modules)');
} else {
    const dirty = execFileSync('git', ['status', '--porcelain', '--', ...files.map((file) => 'utils/' + file)], {
        cwd: repo,
        encoding: 'utf8',
    }).trim();
    if (dirty && !args.has('--allow-dirty'))
        throw new Error('Refusing dirty rule sources; commit or explicitly use --allow-dirty for review');
    const commit =
        execFileSync('git', ['rev-parse', '--short=8', 'HEAD'], { cwd: repo, encoding: 'utf8' }).trim() +
        (dirty ? '-dirty' : '');
    fs.mkdirSync(target, { recursive: true });
    for (const [file, contents] of output) fs.writeFileSync(file, contents);
    const entries = Object.entries(hashes)
        .map(([file, sha]) => `        '${file}': '${sha}',`)
        .join('\n');
    fs.writeFileSync(
        stampPath,
        `// GENERATED by pi-cache/scripts/sync-wake-rule.mjs. Do not edit.\nexport const WAKE_RULE_SYNCED_FROM = {\n    commit: '${commit}',\n    sources: {\n${entries}\n    },\n} as const;\n`,
    );
    console.info('Mirrored wake rules from ' + commit);
}

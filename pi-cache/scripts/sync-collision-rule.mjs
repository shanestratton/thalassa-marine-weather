#!/usr/bin/env node
/**
 * Mirror the app's collision rule into the Pi cache (build 126, 126-04a).
 *
 * utils/collisionRule.ts is the ONE collision rule: the chart's CPA chip, the
 * phone's collision and distress alarms and Calypso all grade with it. The
 * Pi's night watch (pi-cache/src/aisWatch.ts) must grade with exactly the same
 * rule, so this copies the file VERBATIM under a generated header to
 * pi-cache/src/collisionRule/collisionRule.ts and records what it copied in
 * pi-cache/src/collisionRule/syncedFrom.ts (the app commit and the source's
 * sha256).
 *
 * Unlike the router's mirror (scripts/sync-router-engine.mjs) there is no
 * import graph to follow: the rule is pure and dependency-free on purpose, and
 * this script refuses a source that imports anything, so the copy needs no
 * rewriting and no formatter (the source is already prettier-clean). That
 * keeps the drift guard a plain byte comparison:
 * tests/CollisionRulePiMirror.test.ts at the repo root, and --check here.
 *
 * Usage (from the repo root or anywhere):
 *   node pi-cache/scripts/sync-collision-rule.mjs           # rewrite the mirror
 *   node pi-cache/scripts/sync-collision-rule.mjs --check   # exit 1 if it drifted
 *
 * It refuses to copy a source with uncommitted changes (the Pi must run a
 * commit) unless --allow-dirty is given; the stamp then says '-dirty'. The
 * mirror is generated: never edit pi-cache/src/collisionRule/collisionRule.ts
 * or syncedFrom.ts by hand.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PI_CACHE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(PI_CACHE, '..');
const SOURCE = 'utils/collisionRule.ts';
const OUT_DIR = path.join(PI_CACHE, 'src', 'collisionRule');
const MIRROR = path.join(OUT_DIR, 'collisionRule.ts');
const STAMP = path.join(OUT_DIR, 'syncedFrom.ts');

/** Exactly what goes above the copied source (tests/CollisionRulePiMirror.test.ts holds the same lines). */
const HEADER = [
    '// GENERATED by pi-cache/scripts/sync-collision-rule.mjs from utils/collisionRule.ts, copied verbatim below.',
    '// Do not edit here: change utils/collisionRule.ts, then run `node pi-cache/scripts/sync-collision-rule.mjs`.',
    '// tests/CollisionRulePiMirror.test.ts and the script --check fail on any difference.',
    '',
    '',
].join('\n');

const args = new Set(process.argv.slice(2));
const CHECK = args.has('--check');
const ALLOW_DIRTY = args.has('--allow-dirty');

const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const rel = (p) => path.relative(REPO, p).split(path.sep).join('/');
const fail = (message) => {
    console.error(`sync-collision-rule: ${message}`);
    process.exit(1);
};

const source = fs.readFileSync(path.join(REPO, SOURCE), 'utf8');

// A verbatim copy is only safe while the rule stands alone: an import would
// resolve to nothing on the Pi (or worse, to something else).
const importing = source
    .split('\n')
    .map((line, i) => ({ line, n: i + 1 }))
    .filter(
        ({ line }) =>
            /^\s*import[\s{*'"]/.test(line) ||
            /^\s*export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s/.test(line) ||
            /\brequire\(|\bimport\(/.test(line),
    );
if (importing.length > 0) {
    fail(
        `refusing to copy ${SOURCE}: the rule must import nothing, and it does at ${importing
            .map(({ n }) => `line ${n}`)
            .join(', ')}`,
    );
}

const digest = sha256(source);
const mirrorText = HEADER + source;

const stampText = (commit) => `// GENERATED by pi-cache/scripts/sync-collision-rule.mjs. Do not edit.
/** The app commit the Pi's collision rule was copied from, and the sha256 of the source it copied. */
export const COLLISION_RULE_SYNCED_FROM = {
    commit: '${commit}',
    source: '${SOURCE}',
    sha256: '${digest}',
} as const;
`;

if (CHECK) {
    const drift = [];
    const have = fs.existsSync(MIRROR) ? fs.readFileSync(MIRROR, 'utf8') : null;
    if (have === null) drift.push(`missing: ${rel(MIRROR)}`);
    else if (have !== mirrorText) drift.push(`differs: ${rel(MIRROR)}`);
    const stamp = fs.existsSync(STAMP) ? fs.readFileSync(STAMP, 'utf8') : '';
    if (!stamp.includes(`sha256: '${digest}'`)) drift.push(`stale sha256: ${rel(STAMP)}`);
    if (drift.length > 0) {
        console.error(`sync-collision-rule --check: the Pi's copy has drifted from ${SOURCE}:`);
        for (const line of drift) console.error(`  ${line}`);
        console.error('Run: node pi-cache/scripts/sync-collision-rule.mjs');
        process.exit(1);
    }
    const copiedFrom = /commit: '([^']*)'/.exec(stamp)?.[1] ?? '?';
    console.info(`sync-collision-rule --check: in sync (sha256 ${digest.slice(0, 12)}, copied from ${copiedFrom}).`);
    process.exit(0);
}

const git = (...gitArgs) => execFileSync('git', ['-C', REPO, ...gitArgs], { encoding: 'utf8' }).trim();
const dirty = git('status', '--porcelain', '--', SOURCE);
if (dirty && !ALLOW_DIRTY) fail(`${SOURCE} has uncommitted changes:\n${dirty}\n(commit it, or pass --allow-dirty)`);
const commit = git('rev-parse', '--short=8', 'HEAD') + (dirty ? '-dirty' : '');

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.writeFileSync(MIRROR, mirrorText);
fs.writeFileSync(STAMP, stampText(commit));
console.info(
    `sync-collision-rule: ${SOURCE} copied from ${commit} into ${rel(MIRROR)} (sha256 ${digest.slice(0, 12)}).`,
);

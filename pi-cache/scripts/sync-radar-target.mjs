#!/usr/bin/env node
/** One fixed, pure radar policy closure for phone and Pi. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = 'utils/radarTarget.ts';
const stampPath = 'pi-cache/src/radar/syncedFrom.ts';
const read = (path) => readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n');
const files = ['radarTarget', 'radarFeed'].map((name) => {
    const source = read(`utils/${name}.ts`);
    const stripped =
        name === 'radarFeed'
            ? source.replace(/^import\s*\{[^;]*\}\s*from\s*['"]\.\/radarTarget\.js['"];\s*/, '')
            : source;
    if (
        (name === 'radarFeed' && source === stripped) ||
        /^\s*import\s|\brequire\(|\bimport\(|^\s*export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s/m.test(stripped)
    )
        throw Error('Refusing to mirror radar policy outside its fixed pure import closure');
    return {
        sourcePath: `utils/${name}.ts`,
        mirrorPath: `pi-cache/src/radar/${name}.ts`,
        text: `// GENERATED by pi-cache/scripts/sync-radar-target.mjs. Edit utils/${name}.ts only.\n\n` + source,
        sha256: createHash('sha256').update(source).digest('hex'),
    };
});
const [target, feed] = files;
if (process.argv.includes('--check')) {
    const stamp = read(stampPath);
    if (
        files.some((file) => read(file.mirrorPath) !== file.text) ||
        !stamp.includes(`sha256: '${target.sha256}'`) ||
        !stamp.includes(`feedSha256: '${feed.sha256}'`)
    )
        throw Error('Radar target mirror drift: run node pi-cache/scripts/sync-radar-target.mjs');
    console.info(`Radar policy mirrors match ${target.sha256.slice(0, 12)}/${feed.sha256.slice(0, 12)}`);
} else {
    const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim();
    const dirty = !!git('status', '--porcelain', '--', ...files.map((file) => file.sourcePath));
    if (dirty && !process.argv.includes('--allow-dirty'))
        throw Error('Commit radar policy before generating its mirror');
    const commit = git('rev-parse', 'HEAD') + (dirty ? '-dirty' : '');
    for (const file of files) {
        mkdirSync(dirname(resolve(root, file.mirrorPath)), { recursive: true });
        writeFileSync(resolve(root, file.mirrorPath), file.text);
    }
    writeFileSync(
        resolve(root, stampPath),
        `// GENERATED by pi-cache/scripts/sync-radar-target.mjs.\nexport const RADAR_TARGET_SYNCED_FROM = {\n    source: '${sourcePath}',\n    commit: '${commit}',\n    sha256: '${target.sha256}',\n    feedSource: '${feed.sourcePath}',\n    feedSha256: '${feed.sha256}',\n} as const;\n`,
    );
    console.info(`Radar policy mirrored from ${commit} (${target.sha256.slice(0, 12)}/${feed.sha256.slice(0, 12)})`);
}

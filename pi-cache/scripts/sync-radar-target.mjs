#!/usr/bin/env node
/** One dependency-free radar parser/qualification policy for phone and Pi. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sourcePath = 'utils/radarTarget.ts';
const mirrorPath = 'pi-cache/src/radar/radarTarget.ts';
const stampPath = 'pi-cache/src/radar/syncedFrom.ts';
const header = '// GENERATED by pi-cache/scripts/sync-radar-target.mjs. Edit utils/radarTarget.ts only.\n\n';
const read = (path) => readFileSync(resolve(root, path), 'utf8').replace(/\r\n/g, '\n');
const source = read(sourcePath);
if (/^\s*import\s|\brequire\(|\bimport\(|^\s*export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s/m.test(source))
    throw Error('Refusing to mirror radar policy with runtime dependencies');
const sha256 = createHash('sha256').update(source).digest('hex');
if (process.argv.includes('--check')) {
    if (read(mirrorPath) !== header + source || !read(stampPath).includes(`sha256: '${sha256}'`))
        throw Error('Radar target mirror drift: run node pi-cache/scripts/sync-radar-target.mjs');
    console.info(`Radar policy mirror matches ${sha256.slice(0, 12)}`);
} else {
    const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim();
    const dirty = !!git('status', '--porcelain', '--', sourcePath);
    if (dirty && !process.argv.includes('--allow-dirty'))
        throw Error('Commit radar policy before generating its mirror');
    const commit = git('rev-parse', 'HEAD') + (dirty ? '-dirty' : '');
    mkdirSync(dirname(resolve(root, mirrorPath)), { recursive: true });
    writeFileSync(resolve(root, mirrorPath), header + source);
    writeFileSync(
        resolve(root, stampPath),
        `// GENERATED by pi-cache/scripts/sync-radar-target.mjs.\nexport const RADAR_TARGET_SYNCED_FROM = {\n    source: '${sourcePath}',\n    commit: '${commit}',\n    sha256: '${sha256}',\n} as const;\n`,
    );
    console.info(`Radar policy mirrored from ${commit} (${sha256.slice(0, 12)})`);
}

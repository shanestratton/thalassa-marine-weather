#!/usr/bin/env node
/** The app owns this pure rule. The standalone Pi package receives a verbatim, SHA256-checked mirror. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PI = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = path.resolve(PI, '..');
const SOURCE = 'utils/polarLearningRule.ts';
const MIRROR = path.join(PI, 'src/polarLearningRule.ts');
const STAMP = path.join(PI, 'src/polarLearningRuleSyncedFrom.ts');
const HEADER =
    '// GENERATED by pi-cache/scripts/sync-polar-rule.mjs from utils/polarLearningRule.ts.\n// Do not edit: change the app rule, then regenerate this verbatim mirror.\n\n';
const source = fs.readFileSync(path.join(ROOT, SOURCE), 'utf8');
if (/^\s*import[\s{*'"]|^\s*export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s|\brequire\(|\bimport\(/m.test(source))
    throw new Error('The mirrored polar rule must remain dependency-free');
const digest = createHash('sha256').update(source).digest('hex');
const mirror = HEADER + source;
if (process.argv.includes('--check')) {
    if (fs.readFileSync(MIRROR, 'utf8') !== mirror || !fs.readFileSync(STAMP, 'utf8').includes(`sha256: '${digest}'`))
        throw new Error('Polar rule mirror or SHA256 differs. Run node pi-cache/scripts/sync-polar-rule.mjs');
    console.info(`sync-polar-rule --check: in sync (sha256 ${digest.slice(0, 12)}).`);
} else {
    const git = (...args) => execFileSync('git', ['-C', ROOT, ...args], { encoding: 'utf8' }).trim();
    const dirty = git('status', '--porcelain', '--', SOURCE);
    if (dirty && !process.argv.includes('--allow-dirty'))
        throw new Error('Commit the app polar rule first, or use --allow-dirty');
    const commit = git('rev-parse', '--short=8', 'HEAD') + (dirty ? '-dirty' : '');
    fs.writeFileSync(MIRROR, mirror);
    fs.writeFileSync(
        STAMP,
        `// GENERATED by pi-cache/scripts/sync-polar-rule.mjs. Do not edit.\nexport const POLAR_RULE_SYNCED_FROM = {\n    commit: '${commit}',\n    source: '${SOURCE}',\n    sha256: '${digest}',\n} as const;\n`,
    );
    console.info(`sync-polar-rule: copied app rule from ${commit}, sha256 ${digest.slice(0, 12)}.`);
}

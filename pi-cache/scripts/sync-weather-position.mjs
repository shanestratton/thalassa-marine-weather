import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
if (process.argv.slice(2).some((arg) => arg !== '--check'))
    throw new Error('Unsupported weather position mirror argument');
const source = fs.readFileSync(path.join(root, 'utils/weatherPosition.ts'), 'utf8').replace(/\r\n/g, '\n');
const tree = ts.createSourceFile('weatherPosition.ts', source, ts.ScriptTarget.Latest, true);
function visit(node) {
    if (
        ts.isImportDeclaration(node) ||
        ts.isImportEqualsDeclaration(node) ||
        (ts.isExportDeclaration(node) && node.moduleSpecifier) ||
        (ts.isCallExpression(node) &&
            (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
                (ts.isIdentifier(node.expression) && node.expression.text === 'require')))
    )
        throw new Error('Weather position wire must be dependency free');
    ts.forEachChild(node, visit);
}
visit(tree);
const target = path.join(root, 'pi-cache/src/weatherPositionWire.ts');
const output =
    '// GENERATED by pi-cache/scripts/sync-weather-position.mjs from utils/weatherPosition.ts. Do not edit.\n' + source;
if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output)
        throw new Error('Weather position mirror drift');
} else fs.writeFileSync(target, output);

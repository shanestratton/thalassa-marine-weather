#!/usr/bin/env node
/** Keep the standalone Pi on the same dependency-free protocol as the app. */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sourceName = 'utils/signalkProtocol.ts';
const mirrorName = 'pi-cache/src/signalkProtocol.ts';
const stampName = 'pi-cache/src/signalkProtocolSyncedFrom.ts';
const read = (name) => fs.readFileSync(path.join(root, name), 'utf8').replace(/\r\n/g, '\n');
const source = read(sourceName);
if (/^\s*import[\s{*'"]|^\s*export\s+(?:type\s+)?(?:\*|\{[^}]*\})\s+from\s|\brequire\(|\bimport\(/m.test(source))
    throw Error('The portable Signal K protocol must remain dependency-free');
const digest = createHash('sha256').update(source).digest('hex');
const header =
    '// GENERATED by pi-cache/scripts/sync-signalk-protocol.mjs from utils/signalkProtocol.ts.\n// Do not edit: change the app protocol, then regenerate this verbatim mirror.\n\n';
const mirror = header + source;
if (process.argv.includes('--check')) {
    if (read(mirrorName) !== mirror || !read(stampName).includes(`sha256: '${digest}'`))
        throw Error('Signal K protocol mirror or SHA256 differs. Run node pi-cache/scripts/sync-signalk-protocol.mjs');
    console.info(`sync-signalk-protocol --check: in sync (sha256 ${digest.slice(0, 12)}).`);
} else {
    const git = (...args) => execFileSync('git', ['-C', root, ...args], { encoding: 'utf8' }).trim();
    if (git('status', '--porcelain', '--', sourceName))
        throw Error('Commit the canonical app protocol before mirroring');
    const commit = git('log', '-1', '--format=%H', '--', sourceName);
    if (!/^[a-f0-9]{40}$/.test(commit)) throw Error('Canonical Signal K source commit is unavailable');
    fs.writeFileSync(path.join(root, mirrorName), mirror);
    fs.writeFileSync(
        path.join(root, stampName),
        `// GENERATED by pi-cache/scripts/sync-signalk-protocol.mjs. Do not edit.\nexport const SIGNALK_PROTOCOL_SYNCED_FROM = {\n    commit: '${commit}',\n    source: '${sourceName}',\n    sha256: '${digest}',\n} as const;\n`,
    );
    console.info(`sync-signalk-protocol: copied app protocol from ${commit}, sha256 ${digest.slice(0, 12)}.`);
}

/** One bounded manual-zone rule; byte-identical phone/Pi/Edge implementation. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const relative = 'utils/anchorSafeZone.ts';
const source = fs.readFileSync(path.join(root, relative), 'utf8').replaceAll('\r\n', '\n');
const hash = createHash('sha256').update(source).digest('hex');
const generated = `// GENERATED by pi-cache/scripts/sync-anchor-zone.mjs from ${relative}.\n// SHA256 ${hash}\n${source}`;
const targets = ['pi-cache/src/anchorSafeZone.ts', 'supabase/functions/_shared/anchorSafeZone.ts'];
const check = process.argv.includes('--check');
let failed = false;
for (const relative of targets) {
    const target = path.join(root, relative);
    if (check) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== generated) {
            console.error(`Anchor safe-area mirror differs: ${relative}`);
            failed = true;
        }
    } else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, generated);
    }
}
if (failed) process.exitCode = 1;
console.info(`Anchor safe-area mirrors ${check ? 'checked' : 'written'}; ${hash}`);

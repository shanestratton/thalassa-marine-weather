#!/usr/bin/env node
/** Fixed metadata-only protocol. No app auth, Preferences, geometry or provider client. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const names = ['noaaAgreementIdentity', 'noaaCatalogueContract', 'noaaEditionPolicy'];
const check = process.argv.includes('--check'),
    digest = createHash('sha256');
let failed = false;
for (const name of names) {
    const rel = `services/enc/${name}.ts`,
        source = fs.readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/g, '\n');
    digest.update(rel + '\n' + createHash('sha256').update(source).digest('hex') + '\n');
    const target = path.join(root, 'pi-cache/src/noaaEdition', name + '.ts');
    const body =
        '// GENERATED by pi-cache/scripts/sync-noaa-edition-policy.mjs from ' +
        rel +
        '.\n' +
        source.replace(/(from\s+['"])(\.[^'"]+)(['"])/g, (_all, a, s, b) => a + s.replace(/\.ts$/, '') + '.js' + b);
    const expected = execFileSync(
        process.execPath,
        [path.join(root, 'node_modules/prettier/bin/prettier.cjs'), '--stdin-filepath', target],
        { cwd: root, input: body, encoding: 'utf8' },
    );
    if (check) {
        if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== expected) {
            console.error('NOAA edition mirror differs: ' + name);
            failed = true;
        }
    } else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.writeFileSync(target, expected);
    }
}
const target = path.join(root, 'pi-cache/src/noaaEdition/sourceDigest.ts'),
    content = `// GENERATED fixed metadata-only source identity.\nexport const NOAA_EDITION_SOURCE_DIGEST = '${digest.digest('hex')}';\n`;
if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) failed = true;
} else fs.writeFileSync(target, content);
if (failed) process.exit(1);
console.log('NOAA edition mirror ' + (check ? 'verified' : 'written') + '.');

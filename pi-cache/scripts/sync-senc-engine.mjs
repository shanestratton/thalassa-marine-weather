#!/usr/bin/env node
/**
 * Mirror the o-charts SENC parser into the Pi cache, for the chart vault
 * (127-C-d decision 8; the router-engine pattern).
 *
 * tools/senc-extractor is the one SENC parser. Until Pi update 3 the Pi ran it
 * from an older git checkout of this repo (~/thalassa-marine-weather) through
 * decryptBatch, which wrote every decrypted cell to disk. The vault instead
 * opens cells in its own memory with a copy of the parser modules it needs,
 * deployed with pi-cache:
 *
 *   - copies MODULES (and nothing they do not import) from
 *     tools/senc-extractor/src into pi-cache/src/sencEngine/;
 *   - fails if a module imports anything but Node built-ins and the other
 *     mirrored modules (no npm dependency rides the mirror: no npm ci, no
 *     better-sqlite3 rebuild on the Pi);
 *   - records the commit it copied, and a digest of the sources, in
 *     sencEngine/syncedFrom.ts.
 *
 * Usage (from the repo root or anywhere):
 *   node pi-cache/scripts/sync-senc-engine.mjs           # rewrite the mirror
 *   node pi-cache/scripts/sync-senc-engine.mjs --check   # exit 1 if it drifted
 *
 * It refuses to copy parser files with uncommitted changes (the Pi must run a
 * commit), unless --allow-dirty is given for a local experiment.
 * The mirror is generated: never edit pi-cache/src/sencEngine by hand.
 */
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PI_CACHE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(PI_CACHE, '..');
const UPSTREAM = 'tools/senc-extractor/src';
const OUT = path.join(PI_CACHE, 'src', 'sencEngine');
const OUT_REL = path.relative(REPO, OUT);
const SYNCED_FROM = 'syncedFrom.ts';
/** What the vault needs: decrypt (oexserverd), the key XML, provenance, parse and emit. */
const MODULES = [
    'binaryReader.ts',
    'chartProvenance.ts',
    'featureParser.ts',
    'geojsonEmitter.ts',
    'keyFile.ts',
    'mercator.ts',
    'meshOutline.ts',
    'oexserverd.ts',
    'recordTypes.ts',
    's57Attributes.ts',
    's57Classes.ts',
];

const args = new Set(process.argv.slice(2));
const CHECK = args.has('--check');
const ALLOW_DIRTY = args.has('--allow-dirty');
const BUILTINS = new Set(builtinModules);

const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const fail = (message) => {
    console.error(`sync-senc-engine: ${message}`);
    process.exit(1);
};

/** Every import/export specifier in a module (static, side-effect and dynamic forms). */
function specifiersOf(source) {
    const out = [];
    for (const m of source.matchAll(/(?:^|[\s;])(?:import|export)\s[^'"]*?from\s*['"]([^'"]+)['"]/g)) out.push(m[1]);
    for (const m of source.matchAll(/(?:^|[\s;])import\s*['"]([^'"]+)['"]/g)) out.push(m[1]);
    for (const m of source.matchAll(/\bimport\(\s*['"]([^'"]+)['"]\s*\)/g)) out.push(m[1]);
    return out;
}

function readModules() {
    const modules = new Map();
    for (const name of MODULES) {
        const file = path.join(REPO, UPSTREAM, name);
        if (!fs.existsSync(file)) fail(`${UPSTREAM}/${name} is missing`);
        const source = fs.readFileSync(file, 'utf8');
        for (const spec of specifiersOf(source)) {
            if (spec.startsWith('./')) {
                const target = spec.replace(/^\.\//, '').replace(/\.js$/, '.ts');
                if (!MODULES.includes(target))
                    fail(`${name} imports '${spec}', which is not mirrored (add it to MODULES)`);
            } else if (spec.startsWith('node:') ? !BUILTINS.has(spec.slice(5)) : !BUILTINS.has(spec)) {
                fail(`${name} imports the package '${spec}': the vault mirrors no npm dependency`);
            }
        }
        modules.set(name, source);
    }
    return modules;
}

function header(name) {
    return [
        `// GENERATED by pi-cache/scripts/sync-senc-engine.mjs from ${UPSTREAM}/${name}.`,
        '// Do not edit here: change the extractor, then re-run the script (127-C-d decision 8).',
        '',
    ].join('\n');
}

function git(...gitArgs) {
    return execFileSync('git', ['-C', REPO, ...gitArgs], { encoding: 'utf8' }).trim();
}

function prettierFormat(files) {
    // Prettier's own entry run by this node: the extensionless .bin shim cannot be executed on Windows.
    const prettier = path.join(REPO, 'node_modules', 'prettier', 'bin', 'prettier.cjs');
    if (!fs.existsSync(prettier)) fail(`${prettier} is missing — run npm ci at the repo root first`);
    execFileSync(process.execPath, [prettier, '--write', '--log-level', 'warn', ...files], {
        cwd: REPO,
        stdio: 'inherit',
    });
}

const modules = readModules();
const digest = sha256(MODULES.map((name) => `${name}\n${sha256(modules.get(name))}\n`).join(''));

/** The mirror, prettier-formatted (CI runs format:check), written into `dir`. */
function formattedTree(dir) {
    fs.mkdirSync(dir, { recursive: true });
    for (const name of MODULES) fs.writeFileSync(path.join(dir, name), header(name) + modules.get(name));
    prettierFormat(MODULES.map((name) => path.join(dir, name)));
}

const listMirror = () =>
    fs.existsSync(OUT)
        ? fs
              .readdirSync(OUT, { withFileTypes: true })
              .filter((d) => d.isFile())
              .map((d) => d.name)
              .sort()
        : [];

const syncedFromFile = (commit) => `// GENERATED by pi-cache/scripts/sync-senc-engine.mjs. Do not edit.
/** The commit the chart vault's SENC parser was copied from, and a digest of the copied sources. */
export const SENC_ENGINE_SYNCED_FROM = {
    commit: '${commit}',
    modules: ${MODULES.length},
    sourceDigest: '${digest}',
} as const;
`;

if (CHECK) {
    const scratch = fs.mkdtempSync(path.join(PI_CACHE, '.senc-engine-check-'));
    process.on('exit', () => fs.rmSync(scratch, { recursive: true, force: true }));
    formattedTree(scratch);
    const drift = [];
    for (const name of MODULES) {
        const want = fs.readFileSync(path.join(scratch, name), 'utf8');
        const have = fs.existsSync(path.join(OUT, name)) ? fs.readFileSync(path.join(OUT, name), 'utf8') : null;
        if (have === null) drift.push(`missing: ${name}`);
        else if (have !== want) drift.push(`differs: ${name}`);
    }
    for (const name of listMirror()) {
        if (name !== SYNCED_FROM && !MODULES.includes(name)) drift.push(`not part of the mirror: ${name}`);
    }
    const stampPath = path.join(OUT, SYNCED_FROM);
    const stamp = fs.existsSync(stampPath) ? fs.readFileSync(stampPath, 'utf8') : '';
    if (!stamp.includes(`sourceDigest: '${digest}'`)) drift.push(`stale digest: ${SYNCED_FROM}`);
    if (drift.length > 0) {
        console.error(`sync-senc-engine --check: the vault's parser copy has drifted from ${UPSTREAM}:`);
        for (const line of drift) console.error(`  ${line}`);
        console.error('Run: node pi-cache/scripts/sync-senc-engine.mjs');
        process.exit(1);
    }
    const copiedFrom = /commit: '([^']*)'/.exec(stamp)?.[1] ?? '?';
    console.info(`sync-senc-engine --check: in sync (${MODULES.length} modules, copied from ${copiedFrom}).`);
    process.exit(0);
}

const sources = MODULES.map((name) => `${UPSTREAM}/${name}`);
const dirty = git('status', '--porcelain', '--', ...sources);
if (dirty && !ALLOW_DIRTY)
    fail(`parser files have uncommitted changes:\n${dirty}\n(commit them, or pass --allow-dirty)`);
const commit = git('rev-parse', '--short=8', 'HEAD') + (dirty ? '-dirty' : '');

const stale = listMirror().filter((name) => name !== SYNCED_FROM && !MODULES.includes(name));
for (const name of stale) fs.rmSync(path.join(OUT, name));
formattedTree(OUT);
fs.writeFileSync(path.join(OUT, SYNCED_FROM), syncedFromFile(commit));
prettierFormat([path.join(OUT, SYNCED_FROM)]);
console.info(
    `sync-senc-engine: ${MODULES.length} modules copied from ${commit} into ${OUT_REL}` +
        (stale.length ? `; removed ${stale.length} no longer mirrored: ${stale.join(', ')}` : '') +
        '.',
);
